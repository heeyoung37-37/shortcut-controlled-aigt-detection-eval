"""Refresh the offline website payload from the unchanged release files.

Run with Python 3 from any directory. No third-party dependencies or API calls.
The JSONL files remain the benchmark version of record.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
paths = sorted((ROOT / "data").glob("*.jsonl"))
paths += sorted((ROOT / "prompts").glob("*.md"))
paths += [ROOT / "data/README.md", ROOT / "data_generation/README.md", ROOT / "CITATION.cff"]
files = {path.relative_to(ROOT).as_posix(): path.read_text(encoding="utf-8") for path in paths}
output = ROOT / "assets/preview-data.js"
output.write_text(
    "// Generated by build_site.py. Edit canonical data/docs, then rebuild.\n"
    "window.AIGT_PREVIEW_FILES = " + json.dumps(files, ensure_ascii=False, separators=(",", ":")) + ";\n",
    encoding="utf-8",
)
print(f"Built offline content from {len(files)} release files.")
